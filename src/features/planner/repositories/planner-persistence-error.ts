export type PlannerPersistenceErrorCode =
  (typeof PLANNER_PERSISTENCE_ERROR_CODES)[number];

export interface PlannerPersistenceError {
  readonly name: 'PlannerPersistenceError';
  readonly code: PlannerPersistenceErrorCode;
  readonly message: string;
  readonly operation?: string;
  readonly cause?: unknown;
}

export function createPlannerPersistenceError(
  code: PlannerPersistenceErrorCode,
  message: string,
  options: Readonly<{ operation?: string; cause?: unknown }> = {},
): PlannerPersistenceError {
  return Object.freeze({
    name: 'PlannerPersistenceError' as const,
    code,
    message,
    ...(options.operation === undefined
      ? {}
      : { operation: options.operation }),
    ...(options.cause === undefined ? {} : { cause: options.cause }),
  });
}
